import type { ReactNode } from 'react';

type TocItem = {
  title: ReactNode;
  url: string;
  depth: number;
};

type PageDataWithGuide = {
  guide?: boolean;
  guideToc?: unknown;
  toc: TocItem[];
};

function isTocItem(value: unknown): value is TocItem {
  if (!value || typeof value !== 'object') return false;

  const item = value as Record<string, unknown>;
  return typeof item.url === 'string'
    && typeof item.depth === 'number';
}

/**
 * Normalizes the optional guide metadata declared in an MDX frontmatter.
 * A guide may provide a curated outline (`guideToc`) or rely on headings
 * generated by Fumadocs (`toc`).
 */
export function getGuidePageData(data: PageDataWithGuide) {
  const customToc = Array.isArray(data.guideToc) && data.guideToc.every(isTocItem)
    ? data.guideToc
    : undefined;

  return {
    isGuide: data.guide === true,
    toc: customToc ?? data.toc,
  };
}
